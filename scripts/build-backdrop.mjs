#!/usr/bin/env node
/**
 * Build the optional backdrop: a flat vector "starship against space" drawn from
 * primitives, so the console ships art it owns instead of a still from a film.
 *
 *   node scripts/build-backdrop.mjs
 *
 * Deterministic (seeded), no dependencies: the output is one small SVG.
 * Everything is flat fill at low opacity — no gradients, no glow, no shadows —
 * so it sits under the LCARS blocks without breaking the block language.
 */
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "public", "backdrop.svg");

const W = 1600;
const H = 834;

/** deterministic RNG (mulberry32) so the file is reproducible */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** most stars are white; a few carry the console's own amber and ice */
function starTint(pick) {
  if (pick > 0.94) return "#ffce9c";
  if (pick > 0.86) return "#99ccff";
  return "#ffffff";
}

const land = rng(0x1c4a5);
const stars = [];
for (let i = 0; i < 460; i++) {
  const x = +(land() * W).toFixed(1);
  const y = +(land() * H).toFixed(1);
  const r = +(0.6 + land() * 1.5).toFixed(2);
  const o = +(0.12 + land() * 0.4).toFixed(2);
  // a handful of tinted stars keep the field from looking like noise
  const fill = starTint(land());
  stars.push(`<circle cx="${x}" cy="${y}" r="${r}" fill="${fill}" opacity="${o}"/>`);
}

/* falcate nebula bands: flat polygons, very low alpha */
const nebula = [
  { d: "M0 120 L520 40 L760 150 L300 250 Z", fill: "#1d2a44", o: 0.5 },
  { d: "M1120 0 L1600 60 L1600 300 L980 180 Z", fill: "#2a2036", o: 0.42 },
  { d: "M0 690 L420 760 L300 834 L0 834 Z", fill: "#14202c", o: 0.5 },
];

const hull = "#323b50";
const hullLit = "#3d4860";
const edge = "#4a5672";
const glow = "#a9cdff";

/** the ship: saucer + neck + engineering hull + two nacelles, drawn flat */
const ship = `
  <g opacity="0.92">
    <ellipse cx="800" cy="452" rx="252" ry="74" fill="${hull}"/>
    <ellipse cx="800" cy="440" rx="212" ry="56" fill="${hullLit}"/>
    <ellipse cx="800" cy="432" rx="164" ry="38" fill="#1e2431"/>
    <rect x="782" y="500" width="36" height="58" fill="${hull}"/>
    <rect x="700" y="552" width="200" height="96" rx="26" fill="${hull}"/>
    <rect x="722" y="566" width="156" height="50" rx="14" fill="${hullLit}"/>
    <rect x="756" y="600" width="88" height="16" rx="8" fill="#41c4f7" opacity="0.55"/>
    <rect x="470" y="596" width="250" height="30" rx="15" fill="${hull}"/>
    <rect x="880" y="596" width="250" height="30" rx="15" fill="${hull}"/>
    <rect x="404" y="590" width="76" height="42" rx="21" fill="${edge}"/>
    <rect x="1120" y="590" width="76" height="42" rx="21" fill="${edge}"/>
    <rect x="418" y="602" width="22" height="18" rx="9" fill="${glow}" opacity="0.8"/>
    <rect x="1160" y="602" width="22" height="18" rx="9" fill="${glow}" opacity="0.8"/>
    <rect x="498" y="604" width="196" height="14" rx="7" fill="${glow}" opacity="0.28"/>
    <rect x="906" y="604" width="196" height="14" rx="7" fill="${glow}" opacity="0.28"/>
    ${Array.from({ length: 18 }, (_, i) => {
      const x = 622 + i * 20;
      const o = 0.32 + (i % 3) * 0.16;
      return `<rect x="${x}" y="452" width="9" height="4" rx="2" fill="#cfe0f5" opacity="${o.toFixed(2)}"/>`;
    }).join("")}
    ${Array.from({ length: 9 }, (_, i) => {
      const x = 726 + i * 18;
      return `<rect x="${x}" y="578" width="7" height="4" rx="2" fill="#ffce9c" opacity="${(0.3 + (i % 4) * 0.12).toFixed(2)}"/>`;
    }).join("")}
    <circle cx="800" cy="429" r="17" fill="#0e131c"/>
    <circle cx="800" cy="429" r="11" fill="#41c4f7" opacity="0.5"/>
  </g>`;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- generated by scripts/build-backdrop.mjs — flat fills only, no gradients -->
  <rect width="${W}" height="${H}" fill="#05070b"/>
  ${nebula.map((n) => `<path d="${n.d}" fill="${n.fill}" opacity="${n.o}"/>`).join("\n  ")}
  ${stars.join("\n  ")}
  ${ship}
</svg>
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, svg, "utf8");
console.log(`wrote ${OUT} (${(svg.length / 1024).toFixed(1)} KB, ${stars.length} stars)`);
