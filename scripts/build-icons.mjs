const index = new Map();
async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) await walk(p);
    else if (e.name.endsWith(".svg")) {
      const base = e.name.slice(0, -4);
      if (!index.has(base)) index.set(base, p);
      else index.set(base, index.get(base)); // keep first
    }
  }
}
await walk(ICONS_DIR);

const out = {};
const missing = [];
for (const [key, base] of Object.entries(MANIFEST)) {
  const file = index.get(base);
  if (!file) {
    missing.push(`${key} → ${base}`);
    continue;
  }
  const svg = await readFile(file, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "").trim();
  out[key] = inner.replace(/"/g, "'");
}

if (missing.length) {
  console.error("missing icons:\n  " + missing.join("\n  "));
}

const body = `// generated by scripts/build-icons.mjs — do not edit by hand
// source: remixicon ${JSON.parse(await readFile(join(HERE, "..", "node_modules", "remixicon", "package.json"), "utf8")).version}
export const ICONS = {
${Object.entries(out).map(([k, v]) => `  "${k}": "${v}",`).join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`;
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`wrote ${Object.keys(out).length} icons → ${OUT} (${(body.length / 1024).toFixed(1)} KB)`);
